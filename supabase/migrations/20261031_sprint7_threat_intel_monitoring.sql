-- 1. THREAT INDICATORS (IOCs: IP, Domain, URL, Hashes)
CREATE TABLE IF NOT EXISTS public.threat_indicators (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    indicator_type TEXT NOT NULL CHECK (indicator_type IN ('ipv4', 'ipv6', 'domain', 'url', 'sha256', 'sha1', 'md5')),
    indicator_value TEXT NOT NULL,
    source TEXT NOT NULL,
    threat_category TEXT NOT NULL DEFAULT 'malware' CHECK (threat_category IN ('malware', 'phishing', 'c2', 'botnet', 'exploit', 'suspicious', 'ransomware')),
    confidence INTEGER NOT NULL DEFAULT 80 CHECK (confidence BETWEEN 0 AND 100),
    severity TEXT NOT NULL DEFAULT 'High' CHECK (severity IN ('Critical', 'High', 'Medium', 'Low', 'Informational')),
    first_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ,
    description TEXT,
    reference_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_indicator_org_type_val UNIQUE (organization_id, indicator_type, indicator_value)
);

-- 2. THREAT FEEDS (External intelligence sources)
CREATE TABLE IF NOT EXISTS public.threat_feeds (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    feed_name TEXT NOT NULL,
    feed_provider TEXT NOT NULL CHECK (feed_provider IN ('cisa_kev', 'urlhaus', 'malwarebazaar', 'otx', 'custom')),
    feed_url TEXT,
    is_enabled BOOLEAN NOT NULL DEFAULT true,
    sync_interval_hours INTEGER NOT NULL DEFAULT 24,
    last_sync_at TIMESTAMPTZ,
    last_sync_status TEXT NOT NULL DEFAULT 'pending' CHECK (last_sync_status IN ('success', 'failed', 'running', 'pending')),
    indicators_count INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_feed_org_provider UNIQUE (organization_id, feed_provider)
);

-- 3. SECURITY EVENTS (Normalized event stream)
CREATE TABLE IF NOT EXISTS public.security_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    source TEXT NOT NULL CHECK (source IN ('network_discovery', 'vulnerability_scanner', 'auth', 'app_audit', 'telemetry', 'manual')),
    event_type TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'Informational' CHECK (severity IN ('Critical', 'High', 'Medium', 'Low', 'Informational')),
    source_ip TEXT,
    destination_ip TEXT,
    hostname TEXT,
    username TEXT,
    asset_id UUID REFERENCES public.assets(id) ON DELETE SET NULL,
    event_description TEXT NOT NULL,
    event_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. DETECTION RULES (Correlation Engine Rules)
CREATE TABLE IF NOT EXISTS public.detection_rules (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    rule_name TEXT NOT NULL,
    description TEXT,
    severity TEXT NOT NULL DEFAULT 'High' CHECK (severity IN ('Critical', 'High', 'Medium', 'Low')),
    rule_type TEXT NOT NULL CHECK (rule_type IN ('auth_failure_threshold', 'threat_intel_match', 'vuln_risk_correlation', 'asset_anomaly', 'repeated_suspicious_events')),
    is_enabled BOOLEAN NOT NULL DEFAULT true,
    threshold INTEGER NOT NULL DEFAULT 5,
    time_window_seconds INTEGER NOT NULL DEFAULT 300,
    event_conditions JSONB DEFAULT '{}'::jsonb,
    last_triggered_at TIMESTAMPTZ,
    created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. ALERTS (Security Incident Alerts generated by rules/correlation)
CREATE TABLE IF NOT EXISTS public.alerts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    alert_type TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'High' CHECK (severity IN ('Critical', 'High', 'Medium', 'Low', 'Informational')),
    status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Investigating', 'Escalated', 'Resolved', 'False Positive')),
    source TEXT NOT NULL,
    asset_id UUID REFERENCES public.assets(id) ON DELETE SET NULL,
    indicator_id UUID REFERENCES public.threat_indicators(id) ON DELETE SET NULL,
    rule_id UUID REFERENCES public.detection_rules(id) ON DELETE SET NULL,
    related_event_ids UUID[] DEFAULT '{}',
    assigned_to UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    linked_incident_id UUID REFERENCES public.incidents(id) ON DELETE SET NULL,
    confidence INTEGER NOT NULL DEFAULT 80 CHECK (confidence BETWEEN 0 AND 100),
    first_detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. ALERT NOTES (Investigation log)
CREATE TABLE IF NOT EXISTS public.alert_notes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    alert_id UUID NOT NULL REFERENCES public.alerts(id) ON DELETE CASCADE,
    author_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. ALERT HISTORY (State transition audit trail)
CREATE TABLE IF NOT EXISTS public.alert_history (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    alert_id UUID NOT NULL REFERENCES public.alerts(id) ON DELETE CASCADE,
    changed_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    previous_state JSONB,
    new_state JSONB,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

